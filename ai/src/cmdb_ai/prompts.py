def with_current_date(prompt: str, today: date) -> str:
    """在提示词末尾追加当前日期：模型不知道今天是哪天，会把"9 月 21 日"猜成别的年份。

    放在末尾、只精确到天：系统提示词后面跟着整段对话历史，它一变，历史部分就命中不了
    模型服务端的前缀缓存；精确到分钟的话，多轮对话几乎每轮都会失去缓存。
    """
    return f"{prompt}\n当前日期：{today:%Y-%m-%d}（北京时间）\n"
